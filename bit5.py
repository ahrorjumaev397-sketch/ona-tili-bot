# ---------- Yordamchi funksiyalar ----------

def _norm(s: str) -> str:
    for ch in ("‘", "’", "ʻ", "ʼ", "`"):
        s = s.replace(ch, "'")
    return s.strip().lower()


def turkumlar():
    """Barcha turkum nomlari va ulardagi so'zlar soni."""
    return {k: len(v) for k, v in LUGAT.items()}


def jami():
    return sum(len(v) for v in LUGAT.values())


def qidir(soz: str):
    """So'zni barcha turkumlardan qidiradi. [(turkum, soz, izoh), ...]"""
    q = _norm(soz)
    natija = []
    for turkum, d in LUGAT.items():
        for k, v in d.items():
            if _norm(k) == q:
                natija.append((turkum, k, v))
    return natija


def boshlanadi(prefiks: str, limit: int = 10):
    """Berilgan harflardan boshlanuvchi so'zlar."""
    p = _norm(prefiks)
    out = []
    for turkum, d in LUGAT.items():
        for k, v in d.items():
            if _norm(k).startswith(p):
                out.append((turkum, k, v))
                if len(out) >= limit:
                    return out
    return out


